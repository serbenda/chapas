export const IDIOMAS = ["es", "en"];

function idiomaInicial() {
  try {
    const guardado = JSON.parse(localStorage.getItem("vuelta-idioma"));
    if (IDIOMAS.includes(guardado)) return guardado;
  } catch (e) {}
  const nav = (typeof navigator !== "undefined" && (navigator.language || "")) || "";
  return nav.toLowerCase().startsWith("es") ? "es" : "en";
}
let idioma = idiomaInicial();

export function getIdioma() { return idioma; }
export function setIdioma(l) {
  if (!IDIOMAS.includes(l)) return;
  idioma = l;
  try { localStorage.setItem("vuelta-idioma", JSON.stringify(l)); } catch (e) {}
}

/** Texto traducido. {n}, {c}... se sustituyen por vars. Si es una lista, elige una frase al azar. */
export function t(clave, vars) {
  let s = TEXTOS[idioma][clave] ?? TEXTOS.es[clave] ?? clave;
  if (Array.isArray(s)) s = s[Math.floor(Math.random() * s.length)];
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return s;
}

/** Aplica los textos a los elementos marcados en el HTML. */
export function aplicarTextos(raiz = document) {
  raiz.querySelectorAll("[data-t]").forEach(el => { el.textContent = t(el.dataset.t); });
  raiz.querySelectorAll("[data-t-html]").forEach(el => { el.innerHTML = t(el.dataset.tHtml); });   // solo textos propios
  raiz.querySelectorAll("[data-t-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.tAria)); });
  document.documentElement.lang = idioma;
}
